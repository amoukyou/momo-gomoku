// Render the characters used by the game into 1-bit bitmap fonts (C source).
//
// usage: swift mkfont.swift <out.c> <source files...>
// Every printable ASCII character is included, plus each non-ASCII character that appears in
// the given source files. Fonts come from the system (for personal use on your own device).
import AppKit
import CoreText

let args = CommandLine.arguments
guard args.count >= 3 else { print("usage: mkfont.swift out.c sources..."); exit(1) }

var chars = Set<UInt32>((0x20...0x7e).map { UInt32($0) })
for path in args[2...] {
    let text = try String(contentsOfFile: path, encoding: .utf8)
    for s in text.unicodeScalars where s.value > 0x7f && s.value != 0xfeff { chars.insert(s.value) }
}
let sorted = chars.sorted()

struct Spec { let name: String; let size: CGFloat; let face: String; let threshold: UInt8 }
let specs = [
    Spec(name: "font12", size: 12, face: "PingFangSC-Regular", threshold: 110),
    Spec(name: "font16", size: 16, face: "PingFangSC-Medium", threshold: 120),
    Spec(name: "font32", size: 32, face: "PingFangSC-Semibold", threshold: 128),
]

var out = "/* Generated by tools/mkfont.swift -- do not edit. */\n#include \"font.h\"\n\n"

for spec in specs {
    let font = CTFontCreateWithName(spec.face as CFString, spec.size, nil)
    let ascent = CTFontGetAscent(font), descent = CTFontGetDescent(font)
    let lineH = Int(ceil(ascent + descent))
    var glyphDefs: [String] = []
    var bitmaps = ""

    for cp in sorted {
        guard let scalar = Unicode.Scalar(cp) else { continue }
        let str = String(Character(scalar)) as CFString
        var utf16 = Array(String(Character(scalar)).utf16)
        var glyphs = [CGGlyph](repeating: 0, count: utf16.count)
        if !CTFontGetGlyphsForCharacters(font, &utf16, &glyphs, utf16.count) { continue }
        _ = str

        var adv = CGSize.zero
        CTFontGetAdvancesForGlyphs(font, .horizontal, &glyphs, &adv, 1)
        let cellW = max(1, Int(ceil(adv.width)) + 2), cellH = lineH + 2

        // render white-on-black grayscale, then threshold
        var pixels = [UInt8](repeating: 0, count: cellW * cellH)
        let cs = CGColorSpaceCreateDeviceGray()
        let ctx = CGContext(data: &pixels, width: cellW, height: cellH, bitsPerComponent: 8,
                            bytesPerRow: cellW, space: cs, bitmapInfo: CGImageAlphaInfo.none.rawValue)!
        ctx.setFillColor(gray: 1, alpha: 1)
        ctx.setShouldAntialias(true)
        ctx.setShouldSmoothFonts(false)
        var pos = CGPoint(x: 1, y: 1 + descent)
        CTFontDrawGlyphs(font, &glyphs, &pos, 1, ctx)

        // pixels are stored top row first in this context's memory
        var minX = cellW, minY = cellH, maxX = -1, maxY = -1
        for y in 0..<cellH { for x in 0..<cellW where pixels[y * cellW + x] >= spec.threshold {
            minX = min(minX, x); maxX = max(maxX, x); minY = min(minY, y); maxY = max(maxY, y)
        } }
        let ident = "\(spec.name)_\(String(cp, radix: 16))"
        if maxX < 0 {   // blank glyph (space)
            glyphDefs.append("    { 0x\(String(cp, radix: 16)), 0, 0, 0, 0, \(Int(round(adv.width))), 0 },")
            continue
        }
        let w = maxX - minX + 1, h = maxY - minY + 1, stride = (w + 7) / 8
        var bytes: [UInt8] = []
        for y in minY...maxY {
            var row = [UInt8](repeating: 0, count: stride)
            for x in minX...maxX where pixels[y * cellW + x] >= spec.threshold {
                row[(x - minX) / 8] |= UInt8(0x80 >> ((x - minX) % 8))
            }
            bytes += row
        }
        bitmaps += "static const uint8_t \(ident)[] = {" + bytes.map { String(format: "0x%02x", $0) }.joined(separator: ",") + "};\n"
        glyphDefs.append("    { 0x\(String(cp, radix: 16)), \(w), \(h), \(minX - 1), \(minY - 1), \(Int(round(adv.width))), \(ident) },")
    }

    out += bitmaps
    out += "\nstatic const struct glyph \(spec.name)_glyphs[] = {\n" + glyphDefs.joined(separator: "\n") + "\n};\n"
    out += "const struct font \(spec.name) = { \(lineH), \(glyphDefs.count), \(spec.name)_glyphs };\n\n"
}

try out.write(toFile: args[1], atomically: true, encoding: .utf8)
print("wrote \(args[1]): \(sorted.count) characters x \(specs.count) sizes")
